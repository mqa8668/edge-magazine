// Neutral monogram logo: rounded square with the first letter of the site name
// and a small red dot, matching public/favicon.svg. Colors are fixed so the
// mark reads the same in light and dark contexts.
export function LogoMark({
  size = 26,
  letter = "E",
}: {
  size?: number;
  letter?: string;
}) {
  const ch = (Array.from((letter || "E").trim())[0] || "E").toUpperCase();
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 100 100"
      aria-hidden="true"
    >
      <rect width="100" height="100" rx="22" fill="#111111" />
      <text
        x="50"
        y="50"
        dy="0.35em"
        text-anchor="middle"
        font-family="'Playfair Display', Georgia, 'Times New Roman', serif"
        font-size="68"
        font-weight="800"
        fill="#f8f8f6"
      >
        {ch}
      </text>
      <circle cx="80" cy="80" r="6" fill="#d9291b" />
    </svg>
  );
}

export function Icon({
  name,
  size = 12,
  class: cls,
}: {
  name: keyof typeof PATHS | string;
  size?: number;
  class?: string;
}) {
  const body = PATHS[name];
  if (!body) return null;
  return (
    <svg
      class={cls}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      aria-hidden="true"
    >
      {raw(body)}
    </svg>
  );
}
